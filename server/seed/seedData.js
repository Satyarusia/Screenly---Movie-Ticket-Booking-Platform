const seedDB = async () => {
  try {
    const mongoUri = process.env.MONGO_URI;
    if (!mongoUri) {
      console.error("Error: MONGO_URI is not defined in your environment (.env)");
      process.exit(1);
    }
    console.log("Connecting to MongoDB...");
    await mongoose.connect(mongoUri);
    console.log("MongoDB Connected!");

    // 1. Seed Admin User
    const adminEmail = "admin@imovies.com";
    let admin = await User.findOne({ email: adminEmail });
    if (!admin) {
      const hashedPassword = await bcrypt.hash("admin123", 10);
      admin = await User.create({
        name: "Cinema Administrator",
        email: adminEmail,
        password: hashedPassword,
        phone: "9876543210",
        role: "admin",
      });
      await Admin.create({
        user: admin._id,
        adminCode: "ADM-001",
        department: "Cinema Operations",
        lastLogin: new Date(),
      });
      console.log("Default Admin created: admin@imovies.com / admin123");
    } else {
      admin.role = "admin";
      await admin.save();
      console.log("Admin account confirmed: admin@imovies.com");
    }

    // 2. Seed Regular User
    const userEmail = "user@imovies.com";
    let regularUser = await User.findOne({ email: userEmail });
    if (!regularUser) {
      const hashedPassword = await bcrypt.hash("user123", 10);
      regularUser = await User.create({
        name: "Rahul Sharma",
        email: userEmail,
        password: hashedPassword,
        phone: "9123456789",
        role: "user",
      });
      console.log("Default User created: user@imovies.com / user123");
    }

    // 3. Upsert Theatres for all 7 target cities
    const seededTheatres = [];
    for (const t of initialTheatres) {
      const existing = await Theatre.findOneAndUpdate(
        { name: t.name, city: t.city },
        { $set: t },
        { upsert: true, new: true }
      );
      seededTheatres.push(existing);
    }
    console.log(`Verified & seeded ${seededTheatres.length} real multiplexes across 7 cities.`);

    // 4. Upsert Movies
    const seededMovies = [];
    for (const m of initialMovies) {
      const existing = await Movie.findOneAndUpdate(
        { title: m.title },
        { $set: m },
        { upsert: true, new: true }
      );
      seededMovies.push(existing);
    }
    console.log(`Verified & seeded ${seededMovies.length} movies with authentic statuses.`);

    // 5. Seed Shows for bookable movies (Now Showing & Advance Booking)
    const bookableMovies = seededMovies.filter(
      (m) => m.theatricalStatus === "Now Showing" || m.theatricalStatus === "Advance Booking"
    );

    const showCount = await Show.countDocuments();
    if (showCount < 20 && bookableMovies.length > 0) {
      console.log("Seeding schedule of verified shows for each multiplex...");
      const times = [
        { h: 10, m: 15, fmt: "2D" },
        { h: 13, m: 45, fmt: "3D" },
        { h: 17, m: 30, fmt: "IMAX 3D" },
        { h: 21, m: 0, fmt: "Dolby Cinema" },
      ];

      const shows = [];
      seededTheatres.forEach((theatre, tIndex) => {
        for (let day = 0; day < 5; day++) {
          times.forEach((t, sIndex) => {
            const showTime = new Date();
            showTime.setDate(showTime.getDate() + day);
            showTime.setHours(t.h, t.m, 0, 0);

            const movie = bookableMovies[(tIndex + day + sIndex) % bookableMovies.length];
            const screen = theatre.screens && theatre.screens[sIndex % theatre.screens.length]
              ? theatre.screens[sIndex % theatre.screens.length]
              : `Screen ${sIndex + 1}`;

            shows.push({
              movie: movie._id,
              theatre: theatre._id,
              screen,
              format: t.fmt,
              language: movie.language || "Hindi",
              price: theatre.prices?.middle || 250,
              showTime,
              status: "Booking Open",
              bookedSeats: sIndex === 0 ? ["L1", "L2", "M5"] : [],
            });
          });
        }
      });

      await Show.insertMany(shows, { ordered: false }).catch(() => {});
      console.log(`Successfully scheduled shows for all multiplexes!`);
    }

    console.log("Database successfully initialized with production-ready data!");
    await mongoose.disconnect();
    process.exit(0);
  } catch (error) {
    console.error("Seeding error:", error);
    process.exit(1);
  }
};

seedDB();
